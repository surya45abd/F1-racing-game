// Packs games/lights-out-gp.html into game/gameHtml.js so the app works offline-first.
// Run after editing the game: npm run build:game
/* global __dirname */
const fs = require('fs');
const path = require('path');

const src = path.resolve(__dirname, '../games/lights-out-gp.html');
const out = path.resolve(__dirname, '../game/gameHtml.js');

let body = fs.readFileSync(src, 'utf8').replace(/^<meta charset="utf-8">\s*/i, '');
// bundle the 3D engine so the installed app works without an internet connection
const THREE_TAG = '<script src="https://cdn.jsdelivr.net/npm/three@0.160.0/build/three.min.js"></script>';
const threeSrc = fs.readFileSync(path.resolve(__dirname, '../node_modules/three/build/three.min.js'), 'utf8');
if (!body.includes(THREE_TAG)) throw new Error('three.js script tag not found in the game file');
body = body.replace(THREE_TAG, () => '<script>' + threeSrc + '</script>');
const head = [
  '<!doctype html><html lang="en"><head>',
  '<meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">',
  '<style>body{margin:0;font-size:14px}*{-webkit-tap-highlight-color:transparent}</style>',
  '</head><body>',
].join('');
const html = head + body + '</body></html>';

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, '// Generated by scripts/build-game.js. Do not edit by hand.\nexport default ' + JSON.stringify(html) + ';\n');
console.log('Wrote ' + path.relative(process.cwd(), out) + ' (' + Math.round(html.length / 1024) + ' KB)');
